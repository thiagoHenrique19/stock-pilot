CREATE TABLE stock_movement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT                      NOT NULL REFERENCES product (id),
    type          VARCHAR(255)                NOT NULL,
    quantity      INTEGER                     NOT NULL CHECK (quantity <> 0),
    reason        VARCHAR(255),
    reference     VARCHAR(255),
    balance_after INTEGER                     NOT NULL CHECK (balance_after >= 0),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_stock_movement_product_created ON stock_movement (product_id, created_at DESC);

-- Opening balance for products that already had stock before the ledger existed
INSERT INTO stock_movement (product_id, type, quantity, reason, balance_after, created_at)
SELECT id, 'IN', quantity, 'Opening balance', quantity, now()
FROM product
WHERE quantity > 0;
