CREATE TABLE product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(255)   NOT NULL UNIQUE,
    name             VARCHAR(255)   NOT NULL,
    price            NUMERIC(19, 2) NOT NULL CHECK (price >= 0),
    quantity         INTEGER        NOT NULL CHECK (quantity >= 0),
    minimum_quantity INTEGER        NOT NULL CHECK (minimum_quantity >= 0)
);

CREATE TABLE sale (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_method  VARCHAR(255)             NOT NULL,
    discount_amount NUMERIC(19, 2)           NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE sale_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id    BIGINT         NOT NULL REFERENCES sale (id),
    product_id BIGINT         NOT NULL REFERENCES product (id),
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(19, 2) NOT NULL
);

CREATE INDEX idx_sale_created_at ON sale (created_at);
CREATE INDEX idx_sale_item_sale_id ON sale_item (sale_id);
CREATE INDEX idx_product_low_stock ON product (quantity, minimum_quantity);
